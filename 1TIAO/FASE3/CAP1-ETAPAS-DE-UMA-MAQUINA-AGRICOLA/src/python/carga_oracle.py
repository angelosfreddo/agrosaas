def preparar_registros_manejo():
    """Combina o CSV de manejo da Fase 1 com os talhoes JSON da Fase 2."""
    registros = []
    df_f1 = pd.read_csv(config.ARQ_FASE1_MANEJO)
    for row in df_f1.itertuples(index=False):
        registros.append({
            "id_manejo": int(row.id),
            "origem_fase": "FASE_1",
            "codigo_talhao": f"F1-T{int(row.id):02d}",
            "fazenda": "Fazenda Experimental FarmTech",
            "cultura": str(row.cultura),
            "variedade": "Padrao Embrapa",
            "area_m2": float(row.area_m2),
            "area_ha": float(row.area_ha),
            "insumo": str(row.insumo),
            "qtd_insumo": float(row.qtd_insumo),
            "unidade_insumo": str(row.unidade),
            "meta_produtiv_t_ha": 4.5 if str(row.cultura).lower().startswith("cafe") else 9.5,
        })

    base_f2 = json.loads(config.ARQ_FASE2_BASE.read_text(encoding="utf-8"))
    for idx, talhao in enumerate(base_f2.get("talhoes", []), start=101):
        area_ha = float(talhao["area_ha"])
        registros.append({
            "id_manejo": idx,
            "origem_fase": "FASE_2",
            "codigo_talhao": str(talhao["codigo"]),
            "fazenda": str(talhao["fazenda"]),
            "cultura": "Cana-de-acucar",
            "variedade": str(talhao["variedade"]),
            "area_m2": round(area_ha * 10000.0, 2),
            "area_ha": area_ha,
            "insumo": "Vinhaca / Adubacao de Soqueira",
            "qtd_insumo": round(area_ha * 120.0, 2),
            "unidade_insumo": "m3",
            "meta_produtiv_t_ha": float(talhao["produtividade_t_ha"]),
        })
    return registros


def preparar_registros_avaliacao_fase2():
    """Le os arquivos JSON e TXT da Fase 2 e prepara os registros de avaliacao."""
    base_f2 = json.loads(config.ARQ_FASE2_BASE.read_text(encoding="utf-8"))
    coleta_f2 = json.loads(config.ARQ_FASE2_COLETA.read_text(encoding="utf-8"))
    param_f2 = json.loads(config.ARQ_FASE2_PARAMETROS.read_text(encoding="utf-8"))
    preco_atr = float(param_f2.get("economia", {}).get("preco_kg_atr_rs", 1.18))

    linhas_log = [
        l.strip() for l in config.ARQ_FASE2_LOG.read_text(encoding="utf-8").splitlines() if l.strip()
    ]
    resumo_log = linhas_log[0][:245] if linhas_log else "Sem log registrado"

    por_codigo = {}
    for av in base_f2.get("avaliacoes", []) + coleta_f2.get("avaliacoes", []):
        cod = av.get("cod_avaliacao") or f"AV-COLETA-{av['codigo_talhao']}-{av['data_avaliacao']}"
        if cod in por_codigo:
            continue
        am = av.get("amostras", {})
        kg_total = float(av.get("kg_total", sum(am.values())))
        area_m2 = float(av["area_amostrada_m2"])
        perda_t_ha = float(av.get("perda_t_ha", round((kg_total / area_m2) * 10.0, 3)))
        perda_pct = float(av.get("perda_pct", round((perda_t_ha / 85.0) * 100.0, 2)))
        prejuizo_rs = float(av.get("prejuizo_rs", round(perda_t_ha * 50.5 * 135.0 * preco_atr, 2)))
        classe = str(av.get("classificacao", "BAIXA" if perda_pct <= 2.5 else "MODERADA"))
        por_codigo[cod] = {
            "cod_avaliacao": cod,
            "codigo_talhao": str(av["codigo_talhao"]),
            "data_avaliacao": str(av["data_avaliacao"]),
            "tipo_colheita": str(av["tipo_colheita"]),
            "colhedora": str(av.get("colhedora") or ""),
            "operador": str(av.get("operador") or ""),
            "turno": str(av["turno"]),
            "velocidade_kmh": float(av.get("velocidade_kmh") or 0.0),
            "area_amostrada_m2": area_m2,
            "kg_total": kg_total,
            "perda_t_ha": perda_t_ha,
            "perda_pct": perda_pct,
            "prejuizo_rs": prejuizo_rs,
            "classificacao": classe,
            "preco_kg_atr_rs": preco_atr,
            "log_auditoria": resumo_log,
        }
    return list(por_codigo.values())


