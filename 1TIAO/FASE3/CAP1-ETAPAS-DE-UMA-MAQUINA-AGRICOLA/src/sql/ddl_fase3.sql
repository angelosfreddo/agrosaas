-- 1. Tabela de Manejo e Culturas (dados trazidos das Fases 1 e 2)
CREATE TABLE FT3_MANEJO_CULTURA (
    ID_MANEJO           NUMBER(10)     PRIMARY KEY,
    ORIGEM_FASE         VARCHAR2(15)   NOT NULL,
    CODIGO_TALHAO       VARCHAR2(15)   NOT NULL,
    FAZENDA             VARCHAR2(60)   NOT NULL,
    CULTURA             VARCHAR2(30)   NOT NULL,
    VARIEDADE           VARCHAR2(40),
    AREA_M2             NUMBER(12,2)   NOT NULL CHECK (AREA_M2 > 0),
    AREA_HA             NUMBER(10,4)   NOT NULL CHECK (AREA_HA > 0),
    INSUMO              VARCHAR2(60)   NOT NULL,
    QTD_INSUMO          NUMBER(12,2)   NOT NULL CHECK (QTD_INSUMO >= 0),
    UNIDADE_INSUMO      VARCHAR2(15)   NOT NULL,
    META_PRODUTIV_T_HA  NUMBER(8,2)
);

-- 2. Tabela de Leituras Tratadas dos Sensores (S1 Umidade, S2 pH, S3 NPK)
CREATE TABLE FT3_LEITURA_SENSOR (
    ID_LEITURA          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DATA_HORA           TIMESTAMP      NOT NULL UNIQUE,
    CULTURA             VARCHAR2(30)   DEFAULT 'Milho' NOT NULL,
    UMIDADE_BRUTA       NUMBER(6,2),
    UMIDADE_TRATADA     NUMBER(5,2)    NOT NULL CHECK (UMIDADE_TRATADA BETWEEN 0 AND 100),
    UMIDADE_SUAVIZADA   NUMBER(5,2)    NOT NULL CHECK (UMIDADE_SUAVIZADA BETWEEN 0 AND 100),
    PH_BRUTO            NUMBER(5,2),
    PH_TRATADO          NUMBER(4,2)    NOT NULL CHECK (PH_TRATADO BETWEEN 0 AND 14),
    PH_SUAVIZADO        NUMBER(4,2)    NOT NULL CHECK (PH_SUAVIZADO BETWEEN 0 AND 14),
    FOSFORO_OK          NUMBER(1)      NOT NULL CHECK (FOSFORO_OK IN (0, 1)),
    POTASSIO_OK         NUMBER(1)      NOT NULL CHECK (POTASSIO_OK IN (0, 1)),
    NITROGENIO_OK       NUMBER(1)      NOT NULL CHECK (NITROGENIO_OK IN (0, 1)),
    ESTADO_BOMBA        NUMBER(1)      NOT NULL CHECK (ESTADO_BOMBA IN (0, 1)),
    PREVISAO_CHUVA      NUMBER(1)      NOT NULL CHECK (PREVISAO_CHUVA IN (0, 1)),
    ACAO_SISTEMA        VARCHAR2(30)   NOT NULL,
    ORIGEM_REGISTRO     VARCHAR2(15)   NOT NULL,
    REGISTRO_IMPUTADO   NUMBER(1)      DEFAULT 0 NOT NULL CHECK (REGISTRO_IMPUTADO IN (0, 1))
);

-- 3. Tabela de Historico de Acionamentos da Bomba de Irrigacao
CREATE TABLE FT3_ACIONAMENTO_BOMBA (
    ID_ACIONAMENTO      NUMBER(10)     PRIMARY KEY,
    DATA_HORA_INICIO    TIMESTAMP      NOT NULL,
    DATA_HORA_FIM       TIMESTAMP      NOT NULL,
    DURACAO_HORAS       NUMBER(6,2)    NOT NULL CHECK (DURACAO_HORAS > 0),
    UMIDADE_INICIAL     NUMBER(5,2)    NOT NULL,
    UMIDADE_FINAL       NUMBER(5,2)    NOT NULL,
    PH_MEDIO            NUMBER(4,2)    NOT NULL,
    TEVE_FERTIRRIGACAO  NUMBER(1)      NOT NULL CHECK (TEVE_FERTIRRIGACAO IN (0, 1)),
    MODALIDADE          VARCHAR2(25)   NOT NULL,
    VOLUME_AGUA_LITROS  NUMBER(12,2)   NOT NULL CHECK (VOLUME_AGUA_LITROS >= 0),
    VOLUME_AGUA_M3      NUMBER(10,3)   NOT NULL CHECK (VOLUME_AGUA_M3 >= 0)
);

-- 4. Tabela de Avaliacoes de Campo e Logs da Fase 2 (JSON e TXT)
CREATE TABLE FT3_AVALIACAO_FASE2 (
    COD_AVALIACAO       VARCHAR2(30)   PRIMARY KEY,
    CODIGO_TALHAO       VARCHAR2(15)   NOT NULL,
    DATA_AVALIACAO      DATE           NOT NULL,
    TIPO_COLHEITA       VARCHAR2(15)   NOT NULL,
    COLHEDORA           VARCHAR2(20),
    OPERADOR            VARCHAR2(60),
    TURNO               VARCHAR2(10)   NOT NULL,
    VELOCIDADE_KMH      NUMBER(4,1),
    AREA_AMOSTRADA_M2   NUMBER(8,2)    NOT NULL,
    KG_TOTAL            NUMBER(10,2)   NOT NULL,
    PERDA_T_HA          NUMBER(8,3)    NOT NULL,
    PERDA_PCT           NUMBER(6,2)    NOT NULL,
    PREJUIZO_RS         NUMBER(14,2)   NOT NULL,
    CLASSIFICACAO       VARCHAR2(15)   NOT NULL,
    PRECO_KG_ATR_RS     NUMBER(6,2),
    LOG_AUDITORIA       VARCHAR2(250)
);

CREATE INDEX IDX_FT3_LEIT_DATA ON FT3_LEITURA_SENSOR(DATA_HORA);
CREATE INDEX IDX_FT3_LEIT_BOMBA ON FT3_LEITURA_SENSOR(ESTADO_BOMBA);
CREATE INDEX IDX_FT3_ACION_INI ON FT3_ACIONAMENTO_BOMBA(DATA_HORA_INICIO);

