-- 1. TABELA DE CULTURAS
CREATE TABLE FT4_CULTURA (
    ID_CULTURA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_CULTURA VARCHAR2(50) NOT NULL UNIQUE,
    VARIEDADE VARCHAR2(50) NOT NULL,
    CICLO_DIAS NUMBER(4) NOT NULL,
    UMIDADE_MINIMA_PCT NUMBER(5,2) NOT NULL,
    UMIDADE_MAXIMA_PCT NUMBER(5,2) NOT NULL,
    PH_IDEAL_MIN NUMBER(4,2) NOT NULL,
    PH_IDEAL_MAX NUMBER(4,2) NOT NULL
);

-- 2. TABELA DE TALHÕES
CREATE TABLE FT4_TALHAO (
    CODIGO_TALHAO VARCHAR2(20) PRIMARY KEY,
    NOME_TALHAO VARCHAR2(100) NOT NULL,
    AREA_HECTARES NUMBER(8,2) NOT NULL,
    TIPO_SOLO VARCHAR2(50) NOT NULL,
    ID_CULTURA NUMBER NOT NULL,
    STATUS_OPERACIONAL VARCHAR2(30) DEFAULT 'EM_PRODUCAO',
    CONSTRAINT FK_TALHAO_CULTURA FOREIGN KEY (ID_CULTURA) REFERENCES FT4_CULTURA(ID_CULTURA)
);

-- 3. TABELA DE SENSORES IOT
CREATE TABLE FT4_SENSOR (
    CODIGO_SENSOR VARCHAR2(30) PRIMARY KEY,
    CODIGO_TALHAO VARCHAR2(20) NOT NULL,
    TIPO_SENSOR VARCHAR2(50) NOT NULL,
    MODELO_HARDWARE VARCHAR2(50) NOT NULL,
    DATA_INSTALACAO DATE NOT NULL,
    STATUS_ATIVO NUMBER(1) DEFAULT 1,
    CONSTRAINT FK_SENSOR_TALHAO FOREIGN KEY (CODIGO_TALHAO) REFERENCES FT4_TALHAO(CODIGO_TALHAO)
);

-- 4. TABELA DE LEITURAS DE SENSORES (SÉRIE TEMPORAL DA FASE 3 E FASE 4)
CREATE TABLE FT4_LEITURA_SENSOR (
    ID_LEITURA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATA_HORA TIMESTAMP NOT NULL,
    CODIGO_TALHAO VARCHAR2(20) NOT NULL,
    UMIDADE_SOLO NUMBER(5,2) NOT NULL,
    PH_SOLO NUMBER(4,2) NOT NULL,
    FOSFORO_OK NUMBER(1) NOT NULL,
    POTASSIO_OK NUMBER(1) NOT NULL,
    NITROGENIO_OK NUMBER(1) NOT NULL,
    ESTADO_BOMBA NUMBER(1) NOT NULL,
    PREVISAO_CHUVA NUMBER(1) NOT NULL,
    ACAO_SISTEMA VARCHAR2(30) NOT NULL,
    ORIGEM_DADO VARCHAR2(30) DEFAULT 'ESP32_WOKWI',
    CONSTRAINT FK_LEITURA_TALHAO FOREIGN KEY (CODIGO_TALHAO) REFERENCES FT4_TALHAO(CODIGO_TALHAO)
);

-- 5. TABELA DE ACIONAMENTOS DE IRRIGAÇÃO
CREATE TABLE FT4_ACIONAMENTO_IRRIGACAO (
    ID_ACIONAMENTO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATA_HORA_INICIO TIMESTAMP NOT NULL,
    DATA_HORA_FIM TIMESTAMP,
    CODIGO_TALHAO VARCHAR2(20) NOT NULL,
    DURACAO_MINUTOS NUMBER(5) NOT NULL,
    VOLUME_LITROS NUMBER(10,2) NOT NULL,
    MOTIVO_ACIONAMENTO VARCHAR2(50) NOT NULL,
    CONSTRAINT FK_ACIONAMENTO_TALHAO FOREIGN KEY (CODIGO_TALHAO) REFERENCES FT4_TALHAO(CODIGO_TALHAO)
);

-- 6. TABELA DE OCORRÊNCIAS DE CAMPO (COM HASH CRIPTOGRÁFICO DE INTEGRIDADE)
CREATE TABLE FT4_OCORRENCIA_CAMPO (
    ID_OCORRENCIA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATA_HORA TIMESTAMP NOT NULL,
    CODIGO_TALHAO VARCHAR2(20) NOT NULL,
    TIPO_OCORRENCIA VARCHAR2(50) NOT NULL,
    GRAVIDADE VARCHAR2(20) NOT NULL,
    OBSERVACAO VARCHAR2(500) NOT NULL,
    OPERADOR VARCHAR2(50) NOT NULL,
    HASH_INTEGRIDADE VARCHAR2(64) NOT NULL,
    STATUS_TRATAMENTO VARCHAR2(30) DEFAULT 'ABERTO',
    CONSTRAINT FK_OCORRENCIA_TALHAO FOREIGN KEY (CODIGO_TALHAO) REFERENCES FT4_TALHAO(CODIGO_TALHAO)
);

-- 7. TABELA DE PREVISÕES DO MODELO DE MACHINE LEARNING
CREATE TABLE FT4_PREVISAO_MODELO (
    ID_PREVISAO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATA_HORA TIMESTAMP NOT NULL,
    CODIGO_TALHAO VARCHAR2(20) NOT NULL,
    UMIDADE_SOLO_ATUAL NUMBER(5,2) NOT NULL,
    PH_ATUAL NUMBER(4,2) NOT NULL,
    FOSFORO_OK NUMBER(1) NOT NULL,
    POTASSIO_OK NUMBER(1) NOT NULL,
    PREDICAO_IRRIGAR NUMBER(1) NOT NULL,
    PROBABILIDADE_IRRIGAR NUMBER(5,4) NOT NULL,
    CONDICAO_SOLO VARCHAR2(30) NOT NULL,
    MODELO_VERSAO VARCHAR2(50) NOT NULL,
    DECISAO_REGRA_FASE2 NUMBER(1) NOT NULL,
    CONCORDANCIA_REGRA NUMBER(1) NOT NULL,
    CONSTRAINT FK_PREVISAO_TALHAO FOREIGN KEY (CODIGO_TALHAO) REFERENCES FT4_TALHAO(CODIGO_TALHAO)
);

-- 8. TABELA DE LOGS DE AUDITORIA CIBERNÉTICA
CREATE TABLE FT4_LOG_SEGURANCA (
    ID_LOG INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATA_HORA TIMESTAMP NOT NULL,
    EVENTO VARCHAR2(50) NOT NULL,
    USUARIO VARCHAR2(50) NOT NULL,
    IP_ORIGEM VARCHAR2(45) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    DETALHES VARCHAR2(500),
    HASH_LOG VARCHAR2(64) NOT NULL
);

